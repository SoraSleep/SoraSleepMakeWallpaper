import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {createHash} from 'node:crypto';
import {loadRuntime} from './runtime-config.mjs';

const runtime=loadRuntime(),require=createRequire(path.join(runtime.imageDreamRoot,'package.json')),sharp=require('sharp');
const base='http://127.0.0.1:17897';
const health=await(await fetch(base+'/api/health')).json();
assert.equal(health.appId,'com.sorasleep.imagedream');
const status=await(await fetch(base+'/api/image-edits/status')).json();
assert.equal(status.customMask,true);
const downloads=path.join(health.dataRoot,'Downloads');
const fileName=fs.readdirSync(downloads).find(name=>/\.(jpe?g|png)$/i.test(name)&&!name.startsWith('edited_'));
assert.ok(fileName,'Existing source required; never generate a smoke-test image');
const source=path.join(downloads,fileName),bytes=fs.readFileSync(source),hash=createHash('sha256').update(bytes).digest('hex');
const before=await sharp(bytes).ensureAlpha().raw().toBuffer({resolveWithObject:true}),{width,height}=before.info;
const mask=Buffer.alloc(width*height*4);
for(let y=35;y<75;y++)for(let x=35;x<75;x++)if((x-55)**2+(y-55)**2<18**2)mask.fill(255,(y*width+x)*4,(y*width+x)*4+4);
const maskPng=await sharp(mask,{raw:{width,height,channels:4}}).png().toBuffer();
const response=await fetch(base+'/api/image-edits/preview',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({fileName,rect:{x:0,y:0,width:100,height:100},confirmRights:true,method:'ns',radius:3,maskPng:maskPng.toString('base64')})});
const job=await response.json();assert.equal(response.status,200,JSON.stringify(job));
const preview=Buffer.from(await(await fetch(base+job.url)).arrayBuffer()),after=await sharp(preview).ensureAlpha().raw().toBuffer();
let outside=0,inside=0;
for(let i=0;i<width*height;i++)for(let c=0;c<4;c++)if(before.data[i*4+c]!==after[i*4+c])mask[i*4+3]?inside++:outside++;
assert.equal(outside,0);assert.ok(inside>0);assert.equal(createHash('sha256').update(fs.readFileSync(source)).digest('hex'),hash);
const report={passed:true,installedAppReplaced:true,customMask:true,nativeDimensions:{width,height},outsideChangedChannels:outside,insideChangedChannels:inside,originalUnchanged:true,previewOnly:true,newGenerationRequests:0,quality:'Locality test only; no watermark-cleanup certification'};
fs.writeFileSync('real-test-output/landscape-upgrade/installed-mask-report.json',JSON.stringify(report,null,2));
console.log(JSON.stringify(report));
